local function center(text, width)
	local pad = math.max(width - vim.fn.strdisplaywidth(text), 0)
	local left = math.ceil(pad / 2)
	return string.rep(" ", left) .. text .. string.rep(" ", pad - left)
end

-- Random quote centered above the art, as one string for snacks.dashboard
function M.header()
	local lines = {}
	for _, text in ipairs(M.quotes[math.random(#M.quotes)]) do
		table.insert(lines, center(text, 80))
	end
	vim.list_extend(lines, M.art)
	return table.concat(lines, "\n")
end

return M
